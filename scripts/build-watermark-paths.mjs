// Converts the watermark text into SVG path data once, at dev time.
// The image function then draws the watermark without needing any fonts on the
// server (AWS Lambda / Netlify Functions ship with no system fonts).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import opentype from 'opentype.js';

const require = createRequire(import.meta.url);
const TEXT = 'PORTFOLIO PREVIEW · CONFIDENTIAL';
const SIZE = 100; // font size in path units, baseline at y = 0

const fontFile = require.resolve('@fontsource/inter/files/inter-latin-700-normal.woff');
const buf = readFileSync(fontFile);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

// Lay the glyphs out by hand (char map + kerning + tracking) instead of using
// opentype.js shaping, which trips over some of Inter's GSUB lookups.
const scale = SIZE / font.unitsPerEm;
const tracking = 0.06 * SIZE;
const path = new opentype.Path();
let x = 0;
let prev = null;
for (const ch of TEXT) {
  const glyph = font.charToGlyph(ch);
  if (prev) x += font.getKerningValue(prev, glyph) * scale;
  path.extend(glyph.getPath(x, 0, SIZE));
  x += glyph.advanceWidth * scale + tracking;
  prev = glyph;
}
const box = path.getBoundingBox();
const round = (n) => Math.round(n * 10) / 10;

const out = `// Generated by scripts/build-watermark-paths.mjs. Do not edit by hand.
// "${TEXT}" in Inter Bold (SIL Open Font License), font size ${SIZE}, baseline at y = 0.
export const WATERMARK_PATH = ${JSON.stringify(path.toPathData(1))};
export const WATERMARK_BOX = ${JSON.stringify({ x1: round(box.x1), y1: round(box.y1), x2: round(box.x2), y2: round(box.y2) })};
`;
writeFileSync(new URL('../functions/_lib/watermark-paths.js', import.meta.url), out);
console.log('Wrote functions/_lib/watermark-paths.js', out.length, 'bytes', box);
